-- Run in a dedicated demo project. Existing tables must have compatible columns.
create table if not exists public.contacts (
 id bigint generated by default as identity primary key,
 created_at timestamptz default now(),
 name text,
 service text,
 message text,
 priority text
);
alter table public.contacts add column if not exists priority text;
alter table public.contacts enable row level security;
grant select, insert on table public.contacts to service_role;
-- The default identity sequence name for the table created above:
grant usage, select on sequence public.contacts_id_seq to service_role;
